pub(super) fn random() -> String {
    use rand::seq::IndexedRandom as _;
    let mut rng = rand::rng();
    format!(
        "{}-{}",
        ADJECTIVES.choose(&mut rng).expect("not empty"),
        NOUNS.choose(&mut rng).expect("not empty"),
    )
}

#[cfg(test)]
mod tests {
    use super::{ADJECTIVES, NOUNS};

    #[test]
    fn every_generated_app_name_is_a_valid_cloud_app_name() {
        let longest = |words: &[&str]| words.iter().map(|w| w.len()).max().unwrap();
        assert!(longest(ADJECTIVES) + 1 + longest(NOUNS) <= 20);
        for word in ADJECTIVES.iter().chain(NOUNS) {
            assert!(word.bytes().all(|b| b.is_ascii_lowercase()), "{word}");
        }
        assert!(
            ADJECTIVES
                .iter()
                .all(|w| !w.starts_with("system") && !w.starts_with("integrations"))
        );
    }
}
