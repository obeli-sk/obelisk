import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standalone from "ajv/dist/standalone/index.js";
import { build } from "esbuild";
import { compile } from "json-schema-to-typescript";

const contract = JSON.parse(await readFile(new URL("../../assets/openapi/lifecycle.json", import.meta.url)));
const output = process.argv[2];
if (!output) throw new Error("Expected output directory");
const header = "// Generated by scripts/update-api-types.sh. Do not edit.\n";
const models = contract.components.schemas;
const ajv = new Ajv2020({ strict: false, code: { source: true, esm: true }, useDefaults: false });
addFormats(ajv);
ajv.addSchema({ $id: "obelisk-lifecycle", components: contract.components });
const exports = {};
for (const name of Object.keys(models)) {
    ajv.addSchema({ $id: name, $ref: `obelisk-lifecycle#/components/schemas/${name}` });
    exports[`validate${name}`] = name;
}
const validators = standalone(ajv, exports);
const decoders = Object.keys(models).map(name => `
export function parse${name}(value) {
    if (!validate${name}(value)) {
        const error = validate${name}.errors[0];
        throw new TypeError("Invalid ${name} at " + (error.instancePath || "/") + ": " + error.message);
    }
    return value;
}
`).join("");
const routes = [];
for (const [path, operations] of Object.entries(contract.paths)) {
    for (const [method, operation] of Object.entries(operations)) {
        const schema = operation.responses?.["200"]?.content?.["application/json"]?.schema;
        if (schema) {
            const name = schema.$ref.split("/").at(-1);
            const pattern = path.split(/(\{[^}]+\})/).map(part =>
                part.startsWith("{") ? "[^/]+" : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
            ).join("");
            routes.push(`    if (method === ${JSON.stringify(method.toUpperCase())} && new RegExp(${JSON.stringify(`^${pattern}$`)}).test(path)) return parse${name}(value);`);
        }
    }
}
const dispatch = `
export function parseApiResponse(method, path, value) {
    path = path.split("?")[0];
${routes.join("\n")}
    return value;
}
`;
// Bundle Ajv's format helpers so the generated package runs without Node or npm.
const bundled = await build({
    stdin: {
        contents: validators + decoders + dispatch,
        resolveDir: fileURLToPath(new URL(".", import.meta.url)),
        sourcefile: "validators.js",
    },
    bundle: true,
    write: false,
    format: "esm",
    platform: "neutral",
    target: "es2020",
    legalComments: "inline",
});
const formatsLicense = await readFile(new URL("node_modules/ajv-formats/LICENSE", import.meta.url), "utf8");
await writeFile(`${output}/index.js`, header + "/*! Bundled ajv-formats helper:\n" + formatsLicense + "*/\n" + bundled.outputFiles[0].text);
const definitions = JSON.parse(JSON.stringify(models).replaceAll("#/components/schemas/", "#/definitions/"));
const properties = Object.fromEntries(Object.keys(models).map(name => [name, { $ref: `#/definitions/${name}` }]));
const types = await compile({ type: "object", properties, required: Object.keys(models), additionalProperties: false, definitions }, "LifecycleModels", { bannerComment: header.trimEnd() });
const declarations = Object.keys(models).map(name => `export function parse${name}(value: unknown): ${name};`).join("\n");
await writeFile(`${output}/index.d.ts`, types + "\n" + declarations + "\nexport function parseApiResponse(method: string, path: string, value: unknown): unknown;\n");
