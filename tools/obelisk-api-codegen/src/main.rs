use anyhow::{Context, Result};
use serde_json::Value;
use std::collections::{BTreeMap, btree_map::Entry};
use std::path::Path;

const ENDPOINT_SCHEMAS: &[&str] = &[
    "/paths/~1v1~1info/get/responses/200/content/application~1json/schema",
    "/paths/~1v1~1app-policy/get/responses/200/content/application~1json/schema",
    "/paths/~1v1~1deployments~1{deployment_id}~1switch/put/requestBody/content/application~1json/schema",
    "/paths/~1v1~1deployments~1{deployment_id}~1switch/put/responses/200/content/application~1json/schema",
];

fn references(value: &mut Value, pending: &mut Vec<String>) -> Result<()> {
    match value {
        Value::Object(object) => {
            if let Some(Value::String(reference)) = object.get_mut("$ref") {
                let name = reference
                    .strip_prefix("#/components/schemas/")
                    .context("Expected a local OpenAPI component reference")?;
                pending.push(name.to_owned());
                *reference = format!("#/definitions/{name}");
            }
            for value in object.values_mut() {
                references(value, pending)?;
            }
        }
        Value::Array(array) => {
            for value in array {
                references(value, pending)?;
            }
        }
        _ => {}
    }
    Ok(())
}

/// Points `$defs` references at `definitions` and turns `anyOf` into `oneOf`.
/// The app config's untagged enums have disjoint variants; typify reads `anyOf` as a
/// struct of optional flattened variants instead.
/// String patterns are dropped so the types need no regex engine; they are checked by hand.
fn app_config_schema(value: &mut Value) {
    match value {
        Value::Object(object) => {
            if let Some(Value::String(reference)) = object.get_mut("$ref")
                && let Some(name) = reference.strip_prefix("#/$defs/")
            {
                *reference = format!("#/definitions/{name}");
            }
            if matches!(object.get("pattern"), Some(Value::String(_))) {
                object.remove("pattern");
            }
            if let Some(variants) = object.remove("anyOf") {
                object.insert("oneOf".into(), variants);
            }
            object.values_mut().for_each(app_config_schema);
        }
        Value::Array(array) => array.iter_mut().for_each(app_config_schema),
        _ => {}
    }
}

fn main() -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let output = std::env::args().nth(1).context("Expected output path")?;
    let document: Value =
        serde_json::from_slice(&std::fs::read(root.join("assets/openapi/lifecycle.json"))?)?;
    let mut pending = Vec::new();
    for pointer in ENDPOINT_SCHEMAS {
        let mut schema = document
            .pointer(pointer)
            .with_context(|| format!("Missing endpoint schema: {pointer}"))?
            .clone();
        references(&mut schema, &mut pending)?;
    }
    let mut definitions = BTreeMap::<String, schemars::schema::Schema>::new();
    while let Some(name) = pending.pop() {
        if let Entry::Vacant(entry) = definitions.entry(name) {
            let name = entry.key();
            let mut schema = document
                .pointer(&format!("/components/schemas/{name}"))
                .with_context(|| format!("Missing component schema: {name}"))?
                .clone();
            references(&mut schema, &mut pending)?;
            entry.insert(serde_json::from_value(schema)?);
        }
    }
    let mut app: Value =
        serde_json::from_slice(&std::fs::read(root.join("assets/schemas/toml/app.json"))?)?;
    app_config_schema(&mut app);
    let app = app
        .as_object_mut()
        .context("Expected an app config schema object")?;
    app.remove("$schema");
    let app_definitions = app.remove("$defs").context("Missing app config $defs")?;
    let app_definitions = serde_json::from_value::<BTreeMap<String, Value>>(app_definitions)?
        .into_iter()
        .chain([("AppConfigToml".to_owned(), Value::Object(app.clone()))]);
    for (name, schema) in app_definitions {
        let Entry::Vacant(entry) = definitions.entry(name.clone()) else {
            anyhow::bail!("App config type `{name}` collides with an OpenAPI type");
        };
        entry.insert(serde_json::from_value(schema)?);
    }
    let mut settings = typify::TypeSpaceSettings::default();
    settings.with_derive("PartialEq".into());
    settings.with_map_type("::std::collections::BTreeMap");
    let mut types = typify::TypeSpace::new(&settings);
    types.add_ref_types(definitions)?;
    let source = prettyplease::unparse(&syn::parse2(types.to_stream())?);
    std::fs::write(
        output,
        format!("// Generated by scripts/update-api-types.sh. Do not edit.\n{source}"),
    )?;
    Ok(())
}
